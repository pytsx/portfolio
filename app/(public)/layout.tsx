import { Appbar } from "@/components/appbar";
import { Welcome } from "@/components/welcome";
import type { Metadata } from "next";
import { Menu } from "./_src/menu";
import { posts } from "@/lib/posts";
import { connection } from "next/server";
import { Separator } from "@/components/ui/separator";
import Link from "next/link";
import { Footer } from "./_src/footer";

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

async function getPublicMenu() {
  await connection()
  const topPosts = await posts.top(5)

  const menuItems = topPosts.map(post => ({
    title: post.title,
    href: `/blog/${post.id}`,
    // pega os 100 primeiros caracteres da descrição do post
    description: post.content.split(" ").slice(0, 20).join(" ") + (post.content.split(" ").length > 20 ? "..." : "")
  }))

  return Promise.resolve([
    { title: "home", href: "/" },
    { title: "blog", items: menuItems },
    { title: "about", href: "/about" },
    { title: "login", href: "/signin" },
  ])
}


async function getSocials() {

  return Promise.resolve([
      { name: "GitHub", href: "https://github.com/seu-usuario" },
      { name: "LinkedIn", href: "https://linkedin.com/in/seu-usuario" },
      { name: "Twitter", href: "https://twitter.com/seu-usuario" },
    ]
  )
}

export default async function PublicLayout({ children }: LayoutProps<"/">) {

  const menu = await getPublicMenu()
  const socials = await getSocials()

  return (
    <main>
      <Welcome />
      <Appbar>
        <div>acme</div>
        <Menu items={menu} />
      </Appbar>

      {children}
      <Separator className="mb-4" />

      <Footer
        logo={<div>acme</div>}
        socials={socials}
      />
    </main>
  )
}


